# Converts a logo on a white background into an LVGL 8 `TRUE_COLOR_ALPHA` C image
# (16 bit colour w/ `LV_COLOR_16_SWAP`, i.e. RGB565 big-endian + 8 bit alpha).
# White becomes transparent; everything darker than `-Threshold` is fully opaque.
#
# Usage: pwsh tools/img-to-lvgl.ps1 -Src logo.png -Out src/ui/modern/img_logo.c -Name img_logo -Width 84
param(
    [Parameter(Mandatory)][string]$Src,
    [Parameter(Mandatory)][string]$Out,
    [Parameter(Mandatory)][string]$Name,
    [Parameter(Mandatory)][int]$Width,
    [int]$Threshold = 242,  # luminance at/below which a pixel is fully opaque
    [int]$Feather = 12      # luminance range above `Threshold` that fades to transparent
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

function Get-Pixels([System.Drawing.Bitmap]$bmp) {
    $rect = [System.Drawing.Rectangle]::new(0, 0, $bmp.Width, $bmp.Height)
    $data = $bmp.LockBits($rect, 'ReadOnly', [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $bytes = [byte[]]::new($data.Stride * $bmp.Height)
    [System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $bytes, 0, $bytes.Length)
    $bmp.UnlockBits($data)
    return @{ Bytes = $bytes; Stride = $data.Stride }
}

function Resize([System.Drawing.Image]$img, [System.Drawing.Rectangle]$src, [int]$w, [int]$h) {
    $dst = [System.Drawing.Bitmap]::new($w, $h, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($dst)
    $g.Clear([System.Drawing.Color]::White)
    $g.InterpolationMode = 'HighQualityBicubic'
    $g.PixelOffsetMode = 'HighQuality'
    $g.SmoothingMode = 'HighQuality'
    $attr = [System.Drawing.Imaging.ImageAttributes]::new()
    $attr.SetWrapMode('TileFlipXY')  # avoid edge darkening
    $g.DrawImage($img, [System.Drawing.Rectangle]::new(0, 0, $w, $h), $src.X, $src.Y, $src.Width, $src.Height, 'Pixel', $attr)
    $g.Dispose()
    return $dst
}

$img = [System.Drawing.Image]::FromFile((Resolve-Path $Src))

# find the logo's bounding box on a cheap 1/4 scale preview
$scale = 4
$pw = [int]($img.Width / $scale); $ph = [int]($img.Height / $scale)
$preview = Resize $img ([System.Drawing.Rectangle]::new(0, 0, $img.Width, $img.Height)) $pw $ph
$p = Get-Pixels $preview
$x0 = $pw; $y0 = $ph; $x1 = -1; $y1 = -1
for ($y = 0; $y -lt $ph; $y++) {
    for ($x = 0; $x -lt $pw; $x++) {
        $i = $y * $p.Stride + $x * 4
        if ([Math]::Min([Math]::Min($p.Bytes[$i], $p.Bytes[$i + 1]), $p.Bytes[$i + 2]) -lt 250) {
            if ($x -lt $x0) { $x0 = $x }; if ($x -gt $x1) { $x1 = $x }
            if ($y -lt $y0) { $y0 = $y }; if ($y -gt $y1) { $y1 = $y }
        }
    }
}
$preview.Dispose()
if ($x1 -lt 0) { throw "no logo found in $Src" }
$crop = [System.Drawing.Rectangle]::new(($x0 - 1) * $scale, ($y0 - 1) * $scale, ($x1 - $x0 + 3) * $scale, ($y1 - $y0 + 3) * $scale)
$Height = [int][Math]::Round($Width * $crop.Height / $crop.Width)

$bmp = Resize $img $crop $Width $Height
$px = Get-Pixels $bmp

$sb = [System.Text.StringBuilder]::new()
for ($y = 0; $y -lt $Height; $y++) {
    [void]$sb.Append('    ')
    for ($x = 0; $x -lt $Width; $x++) {
        $i = $y * $px.Stride + $x * 4
        # [int] b/c shifting a [byte] overflows silently
        $b = [int]$px.Bytes[$i]; $g = [int]$px.Bytes[$i + 1]; $r = [int]$px.Bytes[$i + 2]
        $lum = [int](0.299 * $r + 0.587 * $g + 0.114 * $b)
        $a = [int][Math]::Clamp(($Threshold + $Feather - $lum) * 255 / $Feather, 0, 255)
        if ($a -lt 255 -and $a -gt 0) {
            # anti-aliased edge: colour was blended w/ white, un-blend it
            $k = $a / 255.0
            $r = [int][Math]::Clamp(($r - 255 * (1 - $k)) / $k, 0, 255)
            $g = [int][Math]::Clamp(($g - 255 * (1 - $k)) / $k, 0, 255)
            $b = [int][Math]::Clamp(($b - 255 * (1 - $k)) / $k, 0, 255)
        }
        $c = (($r -shr 3) -shl 11) -bor (($g -shr 2) -shl 5) -bor ($b -shr 3)
        [void]$sb.AppendFormat('0x{0:x2},0x{1:x2},0x{2:x2},', ($c -shr 8), ($c -band 0xFF), $a)
    }
    [void]$sb.Append("`n")
}
$bmp.Dispose(); $img.Dispose()

$guard = $Name.ToUpper()
@"
// Generated by tools/img-to-lvgl.ps1 from $(Split-Path -Leaf $Src) - do not edit.
// ${Width}x${Height}, LV_IMG_CF_TRUE_COLOR_ALPHA, 16 bit w/ LV_COLOR_16_SWAP

#include "lvgl.h"

#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP != 1
#error "image data assumes LV_COLOR_DEPTH 16 w/ LV_COLOR_16_SWAP"
#endif

static const uint8_t ${Name}_map[] = {
$($sb.ToString())};

const lv_img_dsc_t ${Name} = {
    .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = $Width,
    .header.h = $Height,
    .data_size = sizeof(${Name}_map),
    .data = ${Name}_map,
};
"@ | Set-Content -Encoding utf8NoBOM $Out
"$Out : ${Width}x${Height}"
